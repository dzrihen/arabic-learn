        ("كل شيء تمام","הכל בסדר"),("مش فاضي","לא פנוי"),("بكون عندك","אהיה אצלך"),
        ("خلينا نتقابل","בוא ניפגש"),("بشوفك بكرا","נתראה מחר"),("مع السلامة","להתראות"),
