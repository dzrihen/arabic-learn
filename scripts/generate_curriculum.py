def count_lessons(units):
    return sum(len(u["lessons"]) for u in units)

def expand_level(level_id, title_he, subtitle_he, tracker, target):
    builders = {
        "A1": seeds_a1, "A2": seeds_a2, "B1": seeds_b1,
        "B2": seeds_b2, "C1": seeds_c1, "C2": seeds_c2,
    }
    cefr_map = {
        "A1": ("a1",), "A2": ("a1","a2"), "B1": ("a2","b1"),
        "B2": ("b1","b2"), "C1": ("b2","c1"), "C2": ("c1","c2"),
    }
    cefr = cefr_map[level_id]
    units = []
    if level_id == "A1":
        units.append(alphabet_unit(tracker))
    for item in builders[level_id]():
        uid, th, tr, curated, tip, trows = item
        rows = curated_plus_vocab(tracker, curated, cefr, None, trows)
        units.append(build_unit(level_id, uid, th, tr, rows, tip=tip, per=12 if level_id in ("A1","A2") else 14))

    extra_i = 1
    max_extra = 200
    while count_lessons(units) < target and extra_i <= max_extra:
        unused = [x for x in tracker.bank if tracker.norm(x["lemma"]) not in tracker.introduced]
        band = [x for x in unused if x.get("cefr") in cefr]
        pool = (band or unused)[:120]
        if len(pool) < 8:
            pool = unused[:120] if unused else tracker.sample_band(96) or tracker.bank[:96]
        if len(pool) < 8: break
        rows = []
        for u in pool:
            for ru, he in natural_rows_for_lemma(u)[:1]:
                rows.append((ru, he))
            tracker.mark_lemma(u["lemma"])
            if len(rows) >= 96: break
        uid = f"{level_id.lower()}-u{90+extra_i:02d}"
        units.append(build_unit(level_id, uid, f"אוצר מילים {extra_i}", f"مفردات {extra_i}", rows, tip="חיזוק אוצר מילים", per=12))
        extra_i += 1

    return {"id": level_id, "titleHe": title_he, "subtitleHe": subtitle_he, "units": units}

def write_level(obj, split_at=None):
    lid = obj["id"]
    low = lid.lower()
    units = obj["units"]
    path = os.path.join(OUT, f"{low}.js")
    write_level_js(path, lid, obj["titleHe"], obj["subtitleHe"], units)
    size = os.path.getsize(path)
    mid = max(1, len(units)//2)
    p1 = os.path.join(OUT, f"{low}-part1.js")
    p2 = os.path.join(OUT, f"{low}-part2.js")
    write_level_js(p1, lid, obj["titleHe"], obj["subtitleHe"], units[:mid])
    raw = json.dumps(units[mid:], ensure_ascii=False, separators=(",", ":"))
    with open(p2, "w", encoding="utf-8") as f:
        f.write(f"/* Auto-generated {lid} part2 */\n")
        f.write(f"(function(){{var L=window.RL_LEVEL_{lid};if(!L)return;L.units=L.units.concat({raw});}})();\n")
    if os.path.exists(path):
        os.remove(path)
    return [f"{low}-part1.js", f"{low}-part2.js"], size

