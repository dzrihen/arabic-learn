def mark_rows(tracker, rows):
    for r in rows:
        tracker.mark_text(r[0] if isinstance(r, (list, tuple)) else r.get("ru",""))

EVERYDAY_PATH = os.path.join(os.path.dirname(__file__), "everyday_sentences.json")
EVERYDAY = json.load(open(EVERYDAY_PATH, encoding="utf-8")) if os.path.exists(EVERYDAY_PATH) else {}

def curated_plus_vocab(tracker, curated, cefr, theme, target_rows, uid=None):
    rows = list(curated)
    # hand-written everyday sentences for the unit topic come before any
    # template/vocab filler (see template_guard.py for why)
    seen = {r[0] for r in rows}
    for ru, he in EVERYDAY.get(uid or "", []):
        if ru not in seen and len(rows) < target_rows:
            rows.append((ru, he)); seen.add(ru)
    mark_rows(tracker, rows)
    need = max(0, target_rows - len(rows))
    while need > 0:
        batch = generate_lemma_sentences(tracker, cefr=cefr, theme=theme, count=min(8, need))
        if not batch:
            batch = generate_lemma_sentences(tracker, cefr=cefr, theme=None, count=min(8, need))
        if not batch:
            unused = tracker.pick(need, cefr=cefr) or tracker.pick(need)
            for u in unused[:need]:
                for ru, he in natural_rows_for_lemma(u)[:1]:
                    batch.append((ru, he)); tracker.mark_text(ru)
        rows.extend(batch)
        need = target_rows - len(rows)
        if not batch: break
    head = rows[: max(6, len(curated))]
    tail = rows[len(head):]
    rng = random.Random(hash(theme or "x") % 99991)
    rng.shuffle(tail)
    return head + tail

def build_unit(level, uid, title_he, title_ru, rows, tip=None, per=12, every_cp=CHECKPOINT_EVERY):
    specs = chunk_lessons(title_he, title_ru, rows, per=per, tip=tip)
    specs = with_checkpoint(specs, every=every_cp, pool_phrases=rows, unit_label=title_he[:12])
    idx = int(uid.split("u")[1])
    lessons = make_unit_lessons(level, uid, idx, specs)
    return {"id": uid, "titleHe": title_he, "titleRu": title_ru, "lessons": lessons}

def alphabet_unit(tracker):
    lessons = []
    for i in range(0, len(ALPHABET), 4):
        chunk = ALPHABET[i:i+4]
        if not chunk: break
        idx = i // 4 + 1
        exs = [{
            "type":"alphabet","promptHe":"הכר את האותיות — לחץ לשמיעה",
            "letters":[{"ch":a[0],"nameHe":a[1],"example":a[2]} for a in chunk],
            "tip":"בערבית כותבים מימין לשמאל. האותיות משמשות גם בדיבור הפלסטיני.",
        }]
        for a in chunk:
            exs.append(alphabet_intro(a[0],a[1],a[2],a[3]))
            tracker.mark_text(a[2])
        for a in chunk[:3]:
            others=[x[0] for x in chunk if x[0]!=a[0]][:3]
            exs.append(alphabet_quiz(f"איזו אות? ({a[1]})", a[0], [a[0]]+others))
        for a in chunk[:2]:
            exs.append(speak_repeat(a[2], a[3]))
        lessons.append(lesson(f"a1-u01-l{idx:02d}","A1","a1-u01",f"אותיות {idx}",f"حروف {idx}",exs,xp=10))
    readings = [
        [("ماما في البيت.","אמא בבית."),("بابا عالشغل.","אבא בעבודה."),
         ("هاي مي.","אלה מים."),("وين البيت؟","איפה הבית?"),
         ("أنا هون.","אני כאן."),("مين هاد؟","מי זה?")],
        [("مرحبا!","שלום!"),("شو اسمك؟","איך קוראים לך?"),
         ("اسمي دانيال.","קוראים לי דניאל."),("تشرفنا.","נעים מאוד."),
         ("أنا من إسرائيل.","אני מישראל."),("بعيش هون.","אני גר/ה כאן.")],
        [("هاد صاحبي.","זה החבר שלי."),("هاي أختي.","זאת אחותי."),
         ("هو طالب.","הוא סטודנט."),("هي معلمة.","היא מורה."),
         ("إحنا سوا.","אנחנו ביחד."),("هم بالبيت.","הם בבית.")],
    ]
    for j, rows in enumerate(readings):
        ph = phrases(*[(a,b) for a,b in rows])
        mark_rows(tracker, rows)
        exs = exercises_from_phrases(ph, "קריאה ראשונה", bias="listen")
        lessons.append(lesson(f"a1-u01-l{len(lessons)+1:02d}","A1","a1-u01",f"קריאה {j+1}",f"قراءة {j+1}",exs,xp=12))
    return {"id":"a1-u01","titleHe":"האלפבית הערבי","titleRu":"الحروف العربية","lessons":lessons}

